import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// JobPilot uses ACP as a model transport, not as a coding agent. Keep the
// session outside the career-ops checkout so Codex cannot discover project
// AGENTS.md / repo context, and disable every host/tool feature we do not need.
const CONFIG = `# JobPilot ACP transport-only runtime. Generated by JobPilot; do not add project tools here.
approval_policy = "never"
sandbox_mode = "read-only"

[features]
memories = false
apps = false
browser_use = false
browser_use_external = false
computer_use = false
image_generation = false
multi_agent = false
multi_agent_v2 = false
plugins = false
shell_tool = false
unified_exec = false
skill_search = false
skip_host_skill_discovery = true
hooks = false
tool_suggest = false
sleep_tool = false
view_image = false
code_mode_host = false
workspace_dependencies = false
request_permissions_tool = false

[memories]
generate_memories = false
use_memories = false

[mcp_servers.code-review-graph]
enabled = false
[mcp_servers.omniroute]
enabled = false
[mcp_servers.devspace]
enabled = false
[mcp_servers.devspace2]
enabled = false
[mcp_servers.node_repl]
enabled = false
`;

export function productSessionWorkspace(_root) {
  const base = process.env.LOCALAPPDATA || os.tmpdir();
  const directory = path.join(base, 'JobPilot', 'acp-transport');
  const configDir = path.join(directory, '.codex');
  const file = path.join(configDir, 'config.toml');
  fs.mkdirSync(configDir, { recursive: true });
  const agents = path.join(directory, 'AGENTS.md');
  if (!fs.existsSync(agents)) fs.writeFileSync(agents, '# JobPilot model transport\nNo repository work. Use only the prompt payload.\n');
  let prior = '';
  try { prior = fs.readFileSync(file, 'utf8'); } catch {}
  if (prior !== CONFIG) fs.writeFileSync(file, CONFIG, 'utf8');
  return directory;
}
